package com.hivemc.chunker.conversion.intermediate.column.entity;

import com.google.gson.JsonElement;
import com.hivemc.chunker.conversion.intermediate.column.chunk.itemstack.ChunkerItemStack;
import com.hivemc.chunker.conversion.intermediate.column.entity.type.ChunkerEntityType;
import com.hivemc.chunker.conversion.intermediate.column.entity.type.ChunkerVanillaEntityType;
import it.unimi.dsi.fastutil.bytes.Byte2ObjectAVLTreeMap;
import it.unimi.dsi.fastutil.bytes.Byte2ObjectMap;
import org.jetbrains.annotations.Nullable;

import java.util.EnumSet;
import java.util.Set;

/**
 * A generic entity carrying the data which is common to mobs, armor stands, minecarts and boats so it can be
 * translated between Java and Bedrock. Only fields with a clear equivalent in both editions are kept, data which
 * doesn't translate (AI memories, trades, attributes) is regenerated by the game.
 */
public class MobEntity extends Entity {
    /**
     * Entities which aren't mobs (no spawn egg) but are still handled as a {@link MobEntity}.
     */
    public static final Set<ChunkerVanillaEntityType> EXTRA_TYPES = EnumSet.of(
            ChunkerVanillaEntityType.ARMOR_STAND,
            ChunkerVanillaEntityType.MINECART,
            ChunkerVanillaEntityType.CHEST_MINECART,
            ChunkerVanillaEntityType.HOPPER_MINECART,
            ChunkerVanillaEntityType.FURNACE_MINECART,
            ChunkerVanillaEntityType.TNT_MINECART,
            ChunkerVanillaEntityType.ITEM,
            ChunkerVanillaEntityType.END_CRYSTAL,
            ChunkerVanillaEntityType.OAK_BOAT, ChunkerVanillaEntityType.SPRUCE_BOAT, ChunkerVanillaEntityType.BIRCH_BOAT,
            ChunkerVanillaEntityType.JUNGLE_BOAT, ChunkerVanillaEntityType.ACACIA_BOAT, ChunkerVanillaEntityType.DARK_OAK_BOAT,
            ChunkerVanillaEntityType.MANGROVE_BOAT, ChunkerVanillaEntityType.BAMBOO_RAFT, ChunkerVanillaEntityType.CHERRY_BOAT,
            ChunkerVanillaEntityType.PALE_OAK_BOAT, ChunkerVanillaEntityType.POPLAR_BOAT,
            ChunkerVanillaEntityType.OAK_CHEST_BOAT, ChunkerVanillaEntityType.SPRUCE_CHEST_BOAT,
            ChunkerVanillaEntityType.BIRCH_CHEST_BOAT, ChunkerVanillaEntityType.JUNGLE_CHEST_BOAT,
            ChunkerVanillaEntityType.ACACIA_CHEST_BOAT, ChunkerVanillaEntityType.DARK_OAK_CHEST_BOAT,
            ChunkerVanillaEntityType.MANGROVE_CHEST_BOAT, ChunkerVanillaEntityType.BAMBOO_CHEST_RAFT,
            ChunkerVanillaEntityType.CHERRY_CHEST_BOAT, ChunkerVanillaEntityType.PALE_OAK_CHEST_BOAT,
            ChunkerVanillaEntityType.POPLAR_CHEST_BOAT
    );

    /**
     * Boat woods in Bedrock "Variant" order.
     */
    public static final String[] BOAT_WOODS = {
            "oak", "spruce", "birch", "jungle", "acacia", "dark_oak", "mangrove", "bamboo", "cherry", "pale_oak", "poplar"
    };

    /**
     * Entity types with a storage inventory.
     */
    public static final Set<ChunkerVanillaEntityType> STORAGE_TYPES = EnumSet.of(
            ChunkerVanillaEntityType.CHEST_MINECART,
            ChunkerVanillaEntityType.HOPPER_MINECART,
            ChunkerVanillaEntityType.DONKEY,
            ChunkerVanillaEntityType.MULE,
            ChunkerVanillaEntityType.LLAMA,
            ChunkerVanillaEntityType.TRADER_LLAMA
    );

    /**
     * Get the wood of a boat type.
     *
     * @return the wood name (e.g. "dark_oak") or null if it isn't a boat.
     */
    @Nullable
    public static String boatWood(ChunkerEntityType type) {
        if (!(type instanceof ChunkerVanillaEntityType vanilla)) return null;
        String name = vanilla.name();
        if (name.endsWith("_CHEST_BOAT")) return name.substring(0, name.length() - "_CHEST_BOAT".length()).toLowerCase(java.util.Locale.ROOT);
        if (name.endsWith("_BOAT")) return name.substring(0, name.length() - "_BOAT".length()).toLowerCase(java.util.Locale.ROOT);
        if (name.equals("BAMBOO_RAFT") || name.equals("BAMBOO_CHEST_RAFT")) return "bamboo";
        return null;
    }

    /**
     * Whether a boat type has a chest.
     */
    public static boolean isChestBoat(ChunkerEntityType type) {
        return type instanceof ChunkerVanillaEntityType vanilla
                && (vanilla.name().endsWith("_CHEST_BOAT") || vanilla == ChunkerVanillaEntityType.BAMBOO_CHEST_RAFT);
    }

    /**
     * Get the boat type for a wood.
     *
     * @param wood  the wood name.
     * @param chest whether it has a chest.
     * @return the type, oak if the wood isn't known.
     */
    public static ChunkerVanillaEntityType boatType(String wood, boolean chest) {
        String lower = wood.toLowerCase(java.util.Locale.ROOT);
        if (lower.equals("bamboo")) return chest ? ChunkerVanillaEntityType.BAMBOO_CHEST_RAFT : ChunkerVanillaEntityType.BAMBOO_RAFT;
        try {
            return ChunkerVanillaEntityType.valueOf(lower.toUpperCase(java.util.Locale.ROOT) + (chest ? "_CHEST_BOAT" : "_BOAT"));
        } catch (IllegalArgumentException e) {
            return chest ? ChunkerVanillaEntityType.OAK_CHEST_BOAT : ChunkerVanillaEntityType.OAK_BOAT;
        }
    }

    /**
     * The type to write instead when a format has no specific identifier for a type (formats which store the boat
     * wood as a field rather than in the identifier).
     *
     * @return the fallback type or null if there isn't one.
     */
    @Nullable
    public static ChunkerVanillaEntityType fallbackType(ChunkerEntityType type) {
        if (boatWood(type) == null) return null;
        return isChestBoat(type) ? ChunkerVanillaEntityType.OAK_CHEST_BOAT : ChunkerVanillaEntityType.OAK_BOAT;
    }

    private ChunkerEntityType entityType;
    @Nullable
    private JsonElement customName;
    private boolean customNameVisible;
    @Nullable
    private Float health;
    private boolean baby;
    private int age;
    private boolean persistent;
    private boolean tamed;
    private boolean sitting;
    private boolean saddled;
    private boolean chested;
    private boolean sheared;
    private boolean noAI;
    private boolean silent;
    private boolean invulnerable;
    @Nullable
    private Byte color;
    @Nullable
    private String profession;
    private boolean powered;
    @Nullable
    private String lootTable;
    @Nullable
    private Integer variant;
    @Nullable
    private Integer markVariant;
    @Nullable
    private ChunkerItemStack mainHand;
    @Nullable
    private ChunkerItemStack offHand;
    @Nullable
    private ChunkerItemStack bodyArmor;
    // Feet, legs, chest, head
    private final ChunkerItemStack[] armor = new ChunkerItemStack[4];
    private final Byte2ObjectMap<ChunkerItemStack> inventory = new Byte2ObjectAVLTreeMap<>();

    /**
     * Create a new mob entity.
     *
     * @param entityType the type of the entity.
     */
    public MobEntity(ChunkerEntityType entityType) {
        this.entityType = entityType;
    }

    /**
     * Whether a type should be handled as a mob entity.
     *
     * @param type the type.
     * @return true if it should be.
     */
    public static boolean isHandledType(ChunkerVanillaEntityType type) {
        return type.isVanillaSpawnEgg() || EXTRA_TYPES.contains(type);
    }

    @Override
    public ChunkerEntityType getEntityType() {
        return entityType;
    }

    public void setEntityType(ChunkerEntityType entityType) {
        this.entityType = entityType;
    }

    @Nullable
    public JsonElement getCustomName() {
        return customName;
    }

    public void setCustomName(@Nullable JsonElement customName) {
        this.customName = customName;
    }

    public boolean isCustomNameVisible() {
        return customNameVisible;
    }

    public void setCustomNameVisible(boolean customNameVisible) {
        this.customNameVisible = customNameVisible;
    }

    @Nullable
    public Float getHealth() {
        return health;
    }

    public void setHealth(@Nullable Float health) {
        this.health = health;
    }

    public boolean isBaby() {
        return baby;
    }

    public void setBaby(boolean baby) {
        this.baby = baby;
    }

    /**
     * The age in ticks, negative for babies (Java style).
     */
    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }

    public boolean isPersistent() {
        return persistent;
    }

    public void setPersistent(boolean persistent) {
        this.persistent = persistent;
    }

    public boolean isTamed() {
        return tamed;
    }

    public void setTamed(boolean tamed) {
        this.tamed = tamed;
    }

    public boolean isSitting() {
        return sitting;
    }

    public void setSitting(boolean sitting) {
        this.sitting = sitting;
    }

    public boolean isSaddled() {
        return saddled;
    }

    public void setSaddled(boolean saddled) {
        this.saddled = saddled;
    }

    public boolean isChested() {
        return chested;
    }

    public void setChested(boolean chested) {
        this.chested = chested;
    }

    public boolean isSheared() {
        return sheared;
    }

    public void setSheared(boolean sheared) {
        this.sheared = sheared;
    }

    public boolean isNoAI() {
        return noAI;
    }

    public void setNoAI(boolean noAI) {
        this.noAI = noAI;
    }

    public boolean isSilent() {
        return silent;
    }

    public void setSilent(boolean silent) {
        this.silent = silent;
    }

    public boolean isInvulnerable() {
        return invulnerable;
    }

    public void setInvulnerable(boolean invulnerable) {
        this.invulnerable = invulnerable;
    }

    /**
     * The dye colour index (0-15) of a sheep's wool or a wolf / cat collar.
     */
    @Nullable
    public Byte getColor() {
        return color;
    }

    public void setColor(@Nullable Byte color) {
        this.color = color;
    }

    /**
     * The villager / zombie villager profession, without namespace (e.g. "librarian", "none").
     */
    @Nullable
    public String getProfession() {
        return profession;
    }

    public void setProfession(@Nullable String profession) {
        this.profession = profession;
    }

    /**
     * Whether a creeper is charged.
     */
    public boolean isPowered() {
        return powered;
    }

    public void setPowered(boolean powered) {
        this.powered = powered;
    }

    /**
     * The appearance variant using Bedrock's numbering (horse colour, cat type, parrot / llama / axolotl colour...).
     */
    @Nullable
    public Integer getVariant() {
        return variant;
    }

    public void setVariant(@Nullable Integer variant) {
        this.variant = variant;
    }

    /**
     * The secondary appearance variant using Bedrock's numbering (horse markings).
     */
    @Nullable
    public Integer getMarkVariant() {
        return markVariant;
    }

    public void setMarkVariant(@Nullable Integer markVariant) {
        this.markVariant = markVariant;
    }

    /**
     * The un-generated loot table of a chest minecart / chest boat (Chunker / Java style name).
     */
    @Nullable
    public String getLootTable() {
        return lootTable;
    }

    public void setLootTable(@Nullable String lootTable) {
        this.lootTable = lootTable;
    }

    /**
     * Mobs whose variant is translated.
     */
    public static final Set<ChunkerVanillaEntityType> VARIANT_TYPES = EnumSet.of(
            ChunkerVanillaEntityType.HORSE, ChunkerVanillaEntityType.LLAMA, ChunkerVanillaEntityType.TRADER_LLAMA,
            ChunkerVanillaEntityType.PARROT, ChunkerVanillaEntityType.AXOLOTL, ChunkerVanillaEntityType.CAT,
            ChunkerVanillaEntityType.FOX, ChunkerVanillaEntityType.FROG, ChunkerVanillaEntityType.MOOSHROOM,
            ChunkerVanillaEntityType.RABBIT
    );

    @Nullable
    public ChunkerItemStack getMainHand() {
        return mainHand;
    }

    public void setMainHand(@Nullable ChunkerItemStack mainHand) {
        this.mainHand = mainHand;
    }

    @Nullable
    public ChunkerItemStack getOffHand() {
        return offHand;
    }

    public void setOffHand(@Nullable ChunkerItemStack offHand) {
        this.offHand = offHand;
    }

    /**
     * Body armor: horse armor, wolf armor or a llama's carpet.
     */
    @Nullable
    public ChunkerItemStack getBodyArmor() {
        return bodyArmor;
    }

    public void setBodyArmor(@Nullable ChunkerItemStack bodyArmor) {
        this.bodyArmor = bodyArmor;
    }

    /**
     * Armor in feet, legs, chest, head order (entries may be null).
     */
    public ChunkerItemStack[] getArmor() {
        return armor;
    }

    /**
     * Storage inventory (chest minecarts, hopper minecarts, chested donkeys / mules / llamas) by slot.
     */
    public Byte2ObjectMap<ChunkerItemStack> getInventory() {
        return inventory;
    }

    @Override
    public String toString() {
        return "MobEntity{" + entityType + " at " + getPositionX() + ", " + getPositionY() + ", " + getPositionZ() + "}";
    }
}
